/* ============================================================================
   ЧИСЛО + СУЩЕСТВИТЕЛЬНОЕ ПО-НЕМЕЦКИ
   ----------------------------------------------------------------------------
   «1 neue Knoten», «1 Proben», «1 Antworten» — это не мелочь. Приложение
   готовит к экзамену по немецкому, и такая строка на главном экране читается
   как ошибка того, кого оно учит.

   В немецком множественное число у существительного не всегда видно, а вот
   прилагательное и артикль меняются: ein neuer Knoten / zwei neue Knoten.
   Поэтому в функцию передаётся готовая словоформа, а не корень.
   ========================================================================== */

/** `1 Probe`, `3 Proben` */
export function plural(n: number, one: string, many: string): string {
  return `${n} ${n === 1 ? one : many}`;
}

/** То же, но без числа: `neuer Knoten` / `neue Knoten` для крупной цифры рядом */
export function form(n: number, one: string, many: string): string {
  return n === 1 ? one : many;
}
